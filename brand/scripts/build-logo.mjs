// Builds every logo file from brand/logo/wordmark-paths.json (Satoshi Bold outlines) and the split-coin mark.
// Usage: node brand/scripts/build-logo.mjs
import fs from "node:fs";
import sharp from "sharp";

const PLUM = "#320713", PAPER = "#FFF3F5", INK = "#050102", WHITE = "#FFFFFF";
const wm = JSON.parse(fs.readFileSync("brand/logo/wordmark-paths.json", "utf8"));
const WM_D = wm.glyphs.join(" ");

// Mark: two half discs (r 22) offset 10 horizontally, 6 vertically. Content box x 5..59, y 7..57.
const MARK_TOP = "M15 29a22 22 0 0 1 44 0Z";
const MARK_BOTTOM = "M5 35a22 22 0 0 0 44 0Z";
const markPaths = (fill) => `<path d="${MARK_TOP}" fill="${fill}"/><path d="${MARK_BOTTOM}" fill="${fill}"/>`;

const svg = (vb, body, bg) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" role="img" aria-label="Kondora"><title>Kondora</title>${bg ? `<rect x="${vb.split(" ")[0]}" y="${vb.split(" ")[1]}" width="${vb.split(" ")[2]}" height="${vb.split(" ")[3]}" fill="${bg}"/>` : ""}${body}</svg>\n`;

// Lockup geometry: mark scaled so its height matches the wordmark box height.
const H = wm.height, s = H / 50, markW = 54 * s, gap = H * 0.32;
const lockupW = markW + gap + wm.width;
const lockupBody = (fill) =>
  `<g transform="scale(${s.toFixed(4)}) translate(-5 -7)">${markPaths(fill)}</g><path transform="translate(${(markW + gap).toFixed(2)} 0)" d="${WM_D}" fill="${fill}"/>`;

const pad = (w, h, p) => `${-p} ${-p} ${(w + p * 2).toFixed(2)} ${(h + p * 2).toFixed(2)}`;
const files = {
  "kondora-mark.svg": svg("0 0 64 64", markPaths("currentColor")),
  "kondora-mark-plum.svg": svg("0 0 64 64", markPaths(PLUM)),
  "kondora-mark-paper.svg": svg("0 0 64 64", markPaths(PAPER)),
  "kondora-mark-mono.svg": svg("0 0 64 64", markPaths(INK)),
  "kondora-mark-app.svg": svg("0 0 64 64", markPaths(PAPER), PLUM),
  "kondora-wordmark.svg": svg(pad(wm.width, H, 0), `<path d="${WM_D}" fill="currentColor"/>`),
  "kondora-wordmark-plum.svg": svg(pad(wm.width, H, 0), `<path d="${WM_D}" fill="${PLUM}"/>`),
  "kondora-wordmark-paper.svg": svg(pad(wm.width, H, 0), `<path d="${WM_D}" fill="${PAPER}"/>`),
  "kondora-wordmark-mono.svg": svg(pad(wm.width, H, 0), `<path d="${WM_D}" fill="${INK}"/>`),
  "kondora-lockup.svg": svg(pad(lockupW, H, 0), lockupBody("currentColor")),
  "kondora-lockup-plum-on-paper.svg": svg(pad(lockupW, H, H * 0.6), lockupBody(PLUM), PAPER),
  "kondora-lockup-paper-on-plum.svg": svg(pad(lockupW, H, H * 0.6), lockupBody(PAPER), PLUM),
  "kondora-lockup-mono.svg": svg(pad(lockupW, H, 0), lockupBody(INK)),
  "kondora-lockup-mono-white.svg": svg(pad(lockupW, H, 0), lockupBody(WHITE)),
};

fs.rmSync("brand/logo/mark-path.txt", { force: true });
fs.mkdirSync("public/brand", { recursive: true });
for (const [name, body] of Object.entries(files)) {
  fs.writeFileSync(`brand/logo/${name}`, body);
  if (!name.includes("currentColor") && body.includes("currentColor")) continue;
  fs.writeFileSync(`public/brand/${name}`, body);
}

// PNG exports for the brand page (transparent unless the SVG has a background).
const png = async (name, width) => {
  const out = `public/brand/${name.replace(".svg", "")}.png`;
  await sharp(Buffer.from(files[name]), { density: 600 }).resize({ width }).png().toFile(out);
  fs.copyFileSync(out, `brand/logo/${name.replace(".svg", "")}.png`);
};
for (const n of ["kondora-mark-plum.svg", "kondora-mark-paper.svg", "kondora-mark-app.svg"]) await png(n, 1024);
for (const n of ["kondora-lockup-plum-on-paper.svg", "kondora-lockup-paper-on-plum.svg", "kondora-lockup-mono.svg", "kondora-wordmark-plum.svg"]) await png(n, 2000);

// App icons: paper mark on a plum rounded square.
const icon = (r) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="${r}" fill="${PLUM}"/><g transform="translate(32 32) scale(0.8) translate(-32 -32)">${markPaths(PAPER)}</g></svg>\n`;
fs.writeFileSync("app/icon.svg", icon(14));
await sharp(Buffer.from(icon(0)), { density: 600 }).resize(180, 180).png().toFile("app/apple-icon.png");

// favicon.ico with embedded 16, 32 and 48 PNGs.
const sizes = [16, 32, 48];
const pngs = await Promise.all(sizes.map((z) => sharp(Buffer.from(icon(12)), { density: 600 }).resize(z, z).png().toBuffer()));
const header = Buffer.alloc(6 + 16 * sizes.length);
header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(sizes.length, 4);
let offset = header.length;
sizes.forEach((z, i) => {
  const e = 6 + i * 16;
  header.writeUInt8(z, e); header.writeUInt8(z, e + 1); header.writeUInt16LE(1, e + 4); header.writeUInt16LE(32, e + 6);
  header.writeUInt32LE(pngs[i].length, e + 8); header.writeUInt32LE(offset, e + 12);
  offset += pngs[i].length;
});
fs.writeFileSync("app/favicon.ico", Buffer.concat([header, ...pngs]));

// Shared geometry for React components.
fs.writeFileSync(
  "components/brand/logo-paths.ts",
  `// Generated by brand/scripts/build-logo.mjs. Do not edit by hand.
export const MARK_TOP = "${MARK_TOP}";
export const MARK_BOTTOM = "${MARK_BOTTOM}";
export const WORDMARK_WIDTH = ${wm.width};
export const WORDMARK_HEIGHT = ${H};
export const WORDMARK_GLYPHS = ${JSON.stringify(wm.glyphs)} as const;
export const LOCKUP = { markScale: ${s.toFixed(4)}, wordX: ${(markW + gap).toFixed(2)}, width: ${lockupW.toFixed(2)} } as const;
`,
);
console.log("logo built", Object.keys(files).length, "svgs");
