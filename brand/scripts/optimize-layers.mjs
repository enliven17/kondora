// Optimizes transparent parallax layers into PNG + WebP + AVIF (alpha preserved)
// and writes the size manifest used by components/art/parallax-scene.tsx.
// Usage: node brand/scripts/optimize-layers.mjs <png-dir> [public/art/layers] [lib/art-layers.ts]
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const [src, out = "public/art/layers", manifest = "lib/art-layers.ts"] = process.argv.slice(2);
if (!src) {
  console.error("Usage: node brand/scripts/optimize-layers.mjs <png-dir> [out-dir] [manifest]");
  process.exit(1);
}

/** Max width per layer. Opaque layers are not trimmed. */
const WIDTH = {
  sky: 1920,
  "peaks-far": 1920,
  "peaks-near": 1920,
  clouds: 1600,
  mist: 1920,
  "torn-paper": 1800,
  statue: 1000,
  oracle: 900,
  "hand-scale": 900,
  fragment: 800,
  condor: 900,
  moon: 600,
  "cloud-wisp": 900,
};

fs.mkdirSync(out, { recursive: true });
const sizes = {};
for (const file of fs.readdirSync(src).filter((f) => f.endsWith(".png"))) {
  const name = file.replace(/\.png$/, "");
  const width = WIDTH[name];
  if (!width) continue;
  const input = path.join(src, file);
  const meta = await sharp(input).metadata();
  let pipeline = sharp(input);
  if (meta.hasAlpha) pipeline = pipeline.trim({ threshold: 1 });
  const buffer = await pipeline.resize({ width, withoutEnlargement: true }).png().toBuffer();
  const { width: w, height: h } = await sharp(buffer).metadata();
  const base = path.join(out, name);
  await sharp(buffer).png({ compressionLevel: 9, palette: true, quality: 90, effort: 10 }).toFile(`${base}.png`);
  await sharp(buffer).webp({ quality: 80, alphaQuality: 90, effort: 6 }).toFile(`${base}.webp`);
  await sharp(buffer).avif({ quality: 55, effort: 6 }).toFile(`${base}.avif`);
  const kb = (f) => Math.round(fs.statSync(f).size / 1024);
  console.log(name, `${w}x${h}`, `png ${kb(`${base}.png`)}KB webp ${kb(`${base}.webp`)}KB avif ${kb(`${base}.avif`)}KB`);
  sizes[name] = { width: w, height: h };
}

const names = Object.keys(sizes).sort();
const body = names.map((n) => `  "${n}": { width: ${sizes[n].width}, height: ${sizes[n].height} },`).join("\n");
fs.writeFileSync(
  manifest,
  `// Generated by brand/scripts/optimize-layers.mjs. Do not edit by hand.\n\nexport const ART_LAYERS = {\n${body}\n} as const;\n\nexport type ArtLayerName = keyof typeof ART_LAYERS;\n`,
);
console.log("manifest", manifest);
